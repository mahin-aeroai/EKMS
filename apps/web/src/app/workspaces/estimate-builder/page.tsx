// MMDI ONE Estimate Builder — scoped to IKEA first per the user's request
// to "start with it," then extended to Apple (apple_rate_card, 117 SKUs
// already used by AI Copilot's search_apple_rate_card tool). Pulls real
// products/pricing straight from the customer's own rate card so line
// items aren't hand-typed against a real contract, while still allowing a
// "non-contract / unlisted product" line for anything genuinely outside
// it. Address/GSTIN/attention person are ONE default per customer (see
// customers.address/gstin/default_attention_person) — there is no more
// per-site picker; Job No. (user-typed, permanent, searchable) is what
// now identifies which specific store/job an estimate is for. See
// supabase-estimate-builder-schema.sql + supabase-estimate-builder-jobno-
// productno-migration.sql.
//
// The header fields (Attention person, Quote subject, Job completion time,
// Delivery commitment, Payment terms) and the line-item shape (Design,
// Width/Height in cm with SQFT auto-calculated) were added to match two
// real sample quotes the user shared (IKEA Worli and an Apple Q4
// estimate) — see supabase-estimate-builder-fields-migration.sql.
//
// Design decisions locked in with the user along the way:
// - GST is one flat % applied to (subtotal + transportation + installation)
//   -- no CGST/SGST/IGST split -- that split was explicitly declined in
//   favor of simplicity.
// - Transportation/installation are entered PER LINE ITEM, as a flat
//   amount for that line (not multiplied by quantity) -- "per site/job",
//   matching how a signage installation job is actually costed.
// - Each line is priced either "nos" (quantity * rate -- e.g. Apple's A0
//   Posters/PIM lines, sold per piece) or "sqft" (total sqft * rate --
//   every vinyl/LFG line in both sample quotes): total sqft = (width_in *
//   height_in / 144) * quantity, matching exactly how both samples'
//   SQFT/Amount columns compute (verified against the real numbers in the
//   IKEA sample row by row before building this).
// - Payment terms default to 30 days for IKEA / 45 for Apple (per the
//   user's stated policy) the moment that customer is picked, but stay
//   editable — some estimates will legitimately need a different term.
// - quote_number is generated by public.generate_quote_number() (Postgres
//   side) -- a placeholder `<CODE>-EST-0001` scheme, since the real sample
//   quotes use a location/series-based number (e.g. "Worli-MUM/25-26/
//   IEPL/39") that the user said they'd supply separately.

// "pool" added per "connect Sign Estimator, Cost Sheet, and Estimate
// Builder together -- create a pool where all sign estimates and cost
// sheet products [go], then it is moved to estimate module and there
// select the customer and create estimates." Picking a pool item pre-fills
// the draft below same as "history" does, but from estimate_pool_items
// (supabase-estimate-pool-migration.sql) instead of past sales.
type DraftSource = "contract" | "custom" | "history" | "pool";

// One distinct product previously sold to this customer, per
// sales_transactions -- for customers with no contract/rate card wired up
// (which is most of them; only IKEA/Apple have one so far), this is the
// only source of "what did we actually charge them last time" short of
// digging through old invoices by hand. latestRate/latestDate come from
// whichever of that customer's transactions for this item_code has the
// most recent invoice_date -- exactly "the latest price against whatever
// we sold them," not an average across their whole history (an average
// would blend in old, stale pricing).
interface SalesHistoryProduct {
  itemCode: string | null;
  itemDescription: string | null;
  productCategory: string | null;
  latestRate: number | null;
  latestDate: string | null;
  timesPurchased: number;
}

// SQFT-priced lines can be entered two ways: real Width × Height
// dimensions (the default), or a bulk total SQFT typed directly when
// there's no width/height to multiply -- e.g. quoting "500 sqft of vinyl"
// as one lump area rather than a specific panel size. Purely a UI-side
// toggle: bulkSqft has no DB column of its own, since sqft_total (already
// a stored column either way) carries the final number regardless of
// which entry method produced it.
type SizeEntryMode = "dimensions" | "bulk";

interface DraftLine {
  key: string;
  isContractItem: boolean;
  productNo: string;
  productName: string;
  designName: string;
  description: string;
  additionalDescription: string;
  uom: string;
  calcMode: EstimateCalcMode;
  sizeEntryMode: SizeEntryMode;
  widthCm: number;
  heightCm: number;
  bulkSqft: number;
  unitRate: number;
  quantity: number;
  transportationRate: number;
  installationRate: number;
  // Set when this line came from the estimate pool (Sign Estimator/Cost
  // Sheet) -- lets saveEstimate mark that pool item 'used' once the
  // estimate is actually saved, so it doesn't accidentally get quoted to
  // a second customer too. Undefined for every other source.
  poolItemId?: string;
}

function emptyDraft(): Omit<DraftLine, "key"> {
  return {
    isContractItem: false,
    productNo: "",
    productName: "",
    designName: "",
    description: "",
    additionalDescription: "",
    uom: "",
    calcMode: "sqft",
    sizeEntryMode: "dimensions",
    widthCm: 0,
    heightCm: 0,
    bulkSqft: 0,
    unitRate: 0,
    quantity: 1,
    transportationRate: 0,
    installationRate: 0,
  };
}

// A rate-card row's own UOM text tells us whether it's normally sold per
// piece ("Nos"/"Qty"/"Each") or by area ("SQFT"/"SQM") -- inferred once
// when a product is picked, then always editable/overridable per line.
function inferCalcMode(uom: string | null | undefined): EstimateCalcMode {
  const u = (uom ?? "").toLowerCase();
  return /nos|qty|each|pc|piece/.test(u) ? "nos" : "sqft";
}

const CM_PER_IN = 2.54;
// Width/Height default to cm, but the UOM dropdown (see getSizeUnit in
// pdf.ts) can switch them to feet or inches instead -- e.g. a 10x5 signage
// job can be typed as 10/5 with UOM "Feet" rather than hand-converting to
// 304.8/152.4 cm first. widthCm/heightCm keep their field names for
// minimal disruption to the DB columns/save-load code they map to, but
// hold whichever unit the line's UOM specifies.
function widthIn(l: Pick<DraftLine, "widthCm" | "uom">) {
  const unit = getSizeUnit(l.uom);
  if (unit === "ft") return l.widthCm * 12;
  if (unit === "in") return l.widthCm;
  return l.widthCm / CM_PER_IN;
}
function heightIn(l: Pick<DraftLine, "heightCm" | "uom">) {
  const unit = getSizeUnit(l.uom);
  if (unit === "ft") return l.heightCm * 12;
  if (unit === "in") return l.heightCm;
  return l.heightCm / CM_PER_IN;
}
function sqftTotal(l: Pick<DraftLine, "calcMode" | "sizeEntryMode" | "widthCm" | "heightCm" | "bulkSqft" | "quantity" | "uom">) {
  if (l.calcMode !== "sqft") return 0;
  if (l.sizeEntryMode === "bulk") return l.bulkSqft * l.quantity;
  return (widthIn(l) * heightIn(l)) / 144 * l.quantity;
}
function lineSubtotal(l: Pick<DraftLine, "calcMode" | "sizeEntryMode" | "widthCm" | "heightCm" | "bulkSqft" | "quantity" | "unitRate" | "uom">) {
  return l.calcMode === "sqft" ? sqftTotal(l) * l.unitRate : l.quantity * l.unitRate;
}
function lineTotal(l: DraftLine) {
  return lineSubtotal(l) + l.transportationRate + l.installationRate;
}

function rupee(n: number) {
  return `₹${n.toLocaleString("en-IN", { maximumFractionDigits: 2 })}`;
}

