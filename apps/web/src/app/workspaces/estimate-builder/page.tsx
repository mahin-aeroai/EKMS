  // Small human-readable line built from a pool item's denormalized
  // summary -- for Cost Sheet this is the real physical materials used
  // (substrate, lamination, trims, hardware -- never ink, which is priced
  // in as a service, see CostSheetCalcTab's addToPool), for Sign Estimator
  // it's the category + dims, since that tool doesn't track a materials
  // list the same way.
  // includePrint=false is used when Print is being split out into its own
  // dedicated line item (see pickPoolRow's sign_estimator branch below) --
  // the Signage line's own description shouldn't repeat the print spec that
  // now has its own row.
  function poolItemDescription(item: EstimatePoolItemRow, opts?: { includePrint?: boolean }): string {
    const includePrint = opts?.includePrint ?? true;
    const s = item.summary as {
      description?: string;
      materials?: { name: string; mappedTo: string | null }[];
      categoryLabel?: string;
      dimW?: number;
      dimH?: number;
      dimUnit?: string;
      qty?: number;
      profileName?: string | null;
      printMediaName?: string | null;
      printSqFt?: number | null;
      printRatePerSqft?: number | null;
    };
    if (item.source === "cost_sheet") {
      const materialsLine = (s.materials ?? []).map((m) => (m.mappedTo ? `${m.name}: ${m.mappedTo}` : m.name)).join("; ");
      return [s.description, materialsLine].filter(Boolean).join(" — ") || "Cost Sheet job";
    }
    // Profile and print detail are shown as their own segments (not folded
    // into a single generic line) so the profile spec (e.g. "70mm SEG
    // Profile") and the print media's own sq.ft + ₹/sq.ft rate are each
    // clearly visible on the quote, instead of only the combined total.
    const profileLine = s.profileName ? `Profile: ${s.profileName}` : null;
    const printLine =
      s.printMediaName && s.printSqFt != null && s.printRatePerSqft != null
        ? `Print: ${s.printMediaName} — ${s.printSqFt} sq.ft @ ₹${s.printRatePerSqft}/sq.ft`
        : s.printMediaName ?? null;
    const parts = [
      s.categoryLabel,
      s.dimW && s.dimH ? `${s.dimW}×${s.dimH} ${s.dimUnit ?? ""}`.trim() : null,
      s.qty ? `qty ${s.qty}` : null,
      profileLine,
      includePrint ? printLine : null,
    ];
    return parts.filter(Boolean).join(" — ") || "Sign Estimator job";
  }

  // Picking a pool item pre-fills the draft as a real SQFT line for Cost
  // Sheet items (width x height x qty at the same ₹/sqft rate the job was
  // costed at -- NOT the whole-job total treated as a per-sqft rate, which
  // would massively overprice the line the moment someone entered real
  // dimensions) since that's exactly how Cost Sheet itself prices; Sign
  // Estimator items come in as a "nos" line (LED/profile/print costs don't
  // divide evenly across area the way a BOM's per-sqft material+process
  // cost does, so there's no single clean ₹/sqft rate for the whole job)
  // but still carry the sign's real Width×Height -- "Width height to be
  // mentioned irrespective of price method" -- plus Shipping/Installation
  // split out into their own dedicated columns instead of being buried in
  // one lump sell_amount, same as every other line already does.
  function pickPoolRow(idx: string) {
    setPoolPick(idx);
    const row = poolItems?.[Number(idx)];
    if (!row) return;
    const s = row.summary as {
      width?: number | null;
      height?: number | null;
      uom?: string;
      qty?: number | null;
      unitRatePerSqft?: number | null;
      dimW?: number | null;
      dimH?: number | null;
      dimUnit?: string | null;
      signageSell?: number | null;
      printSell?: number | null;
      printMediaName?: string | null;
      printSqFt?: number | null;
      printRatePerSqft?: number | null;
      shipping?: number | null;
      installSell?: number | null;
    };
    if (row.source === "cost_sheet" && s.width && s.height && s.unitRatePerSqft != null) {
      setDraft((d) => ({
        ...d,
        isContractItem: false,
        productNo: "",
        productName: row.label,
        description: poolItemDescription(row),
        calcMode: "sqft",
        sizeEntryMode: "dimensions",
        // Cost Sheet's own UOM is "FT"/"INC" -- getSizeUnit (shared with
        // the PDF) only recognizes "ft"/"feet" and "in"/"inch", so this
        // maps to what it actually expects rather than passing "INC"
        // through and silently falling back to centimeters.
        uom: s.uom === "INC" ? "in" : "ft",
        widthCm: s.width ?? 0,
        heightCm: s.height ?? 0,
        quantity: s.qty || 1,
        unitRate: s.unitRatePerSqft ?? 0,
      }));
      setPendingPoolExtraLines([]);
    } else if (row.source === "sign_estimator") {
      // Sign Estimator's own dims are in mm/feet/inches, not cm/ft/in --
      // convert mm to cm (getSizeUnit has no "mm" case), pass feet/inches
      // straight through since those units already match.
      const dimUnit = s.dimUnit ?? "mm";
      const uom = dimUnit === "feet" ? "ft" : dimUnit === "inches" ? "in" : "cm";
      const rawW = s.dimW ?? 0;
      const rawH = s.dimH ?? 0;
      const widthCm = dimUnit === "mm" ? rawW / 10 : rawW;
      const heightCm = dimUnit === "mm" ? rawH / 10 : rawH;
      const qty = s.qty || 1;
      const signageSell = s.signageSell ?? 0;
      // Only Print gets split into its own dedicated line item (see
      // pendingPoolExtraLines below) -- Shipping/Installation go right back
      // onto the Signage line's own transportationRate/installationRate
      // fields, using the columns this table already has for exactly that,
      // rather than becoming separate rows too.
      setDraft((d) => ({
        ...d,
        isContractItem: false,
        productNo: "",
        productName: `${row.label} — Signage`,
        description: poolItemDescription(row, { includePrint: false }),
        calcMode: "nos",
        sizeEntryMode: "dimensions",
        uom,
        widthCm,
        heightCm,
        quantity: qty,
        unitRate: qty > 0 ? Math.round(signageSell / qty) : Math.round(signageSell),
        transportationRate: s.shipping ?? 0,
        installationRate: s.installSell ?? 0,
      }));

      const extras: Omit<DraftLine, "key">[] = [];
      if (s.printSell) {
        // Reconstructs the print line at the exact same ₹/sq.ft rate (and
        // total sq.ft) the job was priced at in Sign Estimator, when that
        // detail is available -- quantity × bulkSqft × unitRate then
        // reproduces printSell exactly. Falls back to a plain "nos" line
        // (no real sq.ft/rate to show) when the job was priced at a flat
        // lumpsum instead.
        const havePrintRate = s.printSqFt != null && s.printRatePerSqft != null;
        extras.push({
          ...emptyDraft(),
          productName: `${row.label} — Printing`,
          description: s.printMediaName ?? "Printing",
          calcMode: havePrintRate ? "sqft" : "nos",
          sizeEntryMode: "bulk",
          uom,
          widthCm,
          heightCm,
          bulkSqft: havePrintRate ? s.printSqFt ?? 0 : 0,
          quantity: havePrintRate ? qty : 1,
          unitRate: havePrintRate ? s.printRatePerSqft ?? 0 : s.printSell ?? 0,
        });
      }
      setPendingPoolExtraLines(extras);
    } else {
      setDraft((d) => ({
        ...d,
        isContractItem: false,
        productNo: "",
        productName: row.label,
        description: poolItemDescription(row),
        calcMode: "nos",
        sizeEntryMode: "dimensions",
        widthCm: 0,
        heightCm: 0,
        quantity: 1,
        unitRate: row.sell_amount ?? 0,
      }));
      setPendingPoolExtraLines([]);
    }
    setPendingPoolItemId(row.id);
  }

  function addLine() {
    if (!draft.productName.trim()) {
      toast("danger", "Enter or select a product first");
      return;
    }
    if (draft.calcMode === "sqft" && draft.sizeEntryMode === "dimensions" && (draft.widthCm <= 0 || draft.heightCm <= 0)) {
      toast("danger", "Enter width and height for an area-priced line");
      return;
    }
    if (draft.calcMode === "sqft" && draft.sizeEntryMode === "bulk" && draft.bulkSqft <= 0) {
      toast("danger", "Enter the total SQFT for this line");
      return;
    }
    const poolItemId = source === "pool" ? pendingPoolItemId ?? undefined : undefined;
    setLines((ls) => [
      ...ls,
      {
        ...draft,
        isContractItem: source === "contract",
        key: crypto.randomUUID(),
        poolItemId,
      },
      // Print/Shipping/Installation, precomputed by pickPoolRow -- appended
      // as their own separate line items right alongside the (editable)
      // primary line, all tagged with the same poolItemId so the pool item
      // still gets marked 'used' as one unit on save. Gated on
      // source === "pool" so switching away to another source without
      // clicking a new pool item never re-injects stale leftover extras.
      ...(source === "pool" ? pendingPoolExtraLines.map((l) => ({ ...l, isContractItem: false, key: crypto.randomUUID(), poolItemId })) : []),
    ]);
    setDraft(emptyDraft());
    setPendingPoolExtraLines([]);
    setRateCardPick("");
    setHistoryPick("");
    setPoolPick("");
    setPendingPoolItemId(null);
  }

  function removeLine(key: string) {
    setLines((ls) => ls.filter((l) => l.key !== key));
  }

  const subtotal = lines.reduce((s, l) => s + lineSubtotal(l), 0);
  const transportationTotal = lines.reduce((s, l) => s + l.transportationRate, 0);
